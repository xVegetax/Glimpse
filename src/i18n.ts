export function t(key: string, fallback?: string): string {
  const dict = TRANSLATIONS[activeLanguage] ?? TRANSLATIONS.fr;
  return dict[key] ?? fallback ?? key;
}

export function getCurrentLanguage(): LangCode {
  return activeLanguage;
}

export function applyLanguage(rawLang: string): void {
  const lang = (rawLang in TRANSLATIONS ? rawLang : "fr") as LangCode;
  activeLanguage = lang;
  const dict = TRANSLATIONS[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = "ltr";

  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (key && dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (key && dict[key]) {
      el.title = dict[key];
    }
  });

  document.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (key && dict[key]) {
      el.placeholder = dict[key];
    }
  });
}
